BEGIN;
CREATE TABLE carriers (
 id UUID PRIMARY KEY, code VARCHAR(80) NOT NULL UNIQUE CHECK(code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 name VARCHAR(150) NOT NULL CHECK(length(btrim(name))>0),
 created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE sim_categories (
 id UUID PRIMARY KEY, code VARCHAR(80) NOT NULL UNIQUE CHECK(code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
 name VARCHAR(150) NOT NULL CHECK(length(btrim(name))>0),
 created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMIT;
